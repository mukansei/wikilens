package io.wikilens.index

/**
 * 필드별 가중치. 앵커 > 제목 > 본문.
 *
 * ## 앵커를 가장 높게 두는 것은 문헌이 뒷받침한다
 *
 * 들어오는 앵커 텍스트를 모아 하나의 "앵커 문서" 로 색인하면 known-item·site
 * finding 에서 본문보다 강하다 — Craswell, Hawking, Robertson, *Effective site
 * finding using link anchor information*, SIGIR '01.
 * https://dl.acm.org/doi/10.1145/383952.383999
 * `ALIASES.md`(다른 문서가 이 페이지를 부르는 이름)가 그 구조다.
 *
 * **다만 `4.0`·`3.0`·`1.0` 이라는 구체값의 근거는 여전히 여기 없다.** 문헌은
 * "앵커가 강하다" 를 말하지 배수를 정하지 않는다. 최초 커밋부터 유도 없이 들어
 * 있고, 그것을 보고 "손으로 정한 값" 이라 단정했던 적이 있다 — 출처를 모르는
 * 것과 손으로 정해진 것은 다르다(`조용히 실패 28`).
 *
 * ## 합치는 방식에 알려진 결함이 있다 — 고치지 않았다
 *
 * 지금은 **필드별 BM25 점수를 가중 합산**한다(`MultiFieldQueryParser` + OR):
 *
 *     score = 4·BM25(anchor) + 3·BM25(title) + 1·BM25(body)
 *
 * 문헌은 이 방식이 **일부 질의 항에 과한 가중을 준다**고 지적한다. BM25 의 tf
 * 포화가 비선형인데 점수를 나중에 더하면 포화가 필드마다 따로 걸리기 때문이다.
 * 대신 **tf 를 포화 전에 가중**하라는 것이 BM25F 다 — Robertson, Zaragoza,
 * Taylor, *Simple BM25 extension to multiple weighted fields*, CIKM '04, pp.42–49.
 *
 *     BM25F:  tf' = 4·tf(anchor) + 3·tf(title) + 1·tf(body)  →  BM25(tf')
 *
 * **이 결함이 실제로 관측된다.** D28 의 G05 오답은 제목과 앵커가 같은 문자열이라
 * 같은 항이 두 필드에서 각각 포화를 거친 뒤 더해진다 — 문헌이 말하는 그 경우다.
 *
 * **그래도 안 바꿨다.** ① Lucene 의 `MultiFieldQueryParser` 로는 BM25F 가 안 되고
 * 색인 구조나 커스텀 `Similarity` 가 필요하다 — 작은 변경이 아니다. ② 실측에서
 * **정답을 결과 밖으로 밀어낸 사례가 0건**이라, 이론적 결함이 이 코퍼스에서 손해로
 * 나타난 증거는 G05 하나다. ③ 바꾸면 이 세 숫자가 다른 의미가 되어 전부 다시
 * 재야 한다.
 *
 * ## 중복을 입력에서 줄여 보려다 반대 결과를 얻었다 (2026-08-26)
 *
 * 제목과 문자열이 같은 앵커(코웨이 75% · ONAP 71%)를 빼면 필드 간 중복이 줄 것으로
 * 보고 재봤다. **두 코퍼스가 반대로 갈렸다** — 코웨이 상위10 `17 → 21`, ONAP
 * `8 → 5`. 넣지 않았다.
 *
 * **같은 문자열도 필드가 다르면 다른 정보다.** IDF 가 필드별로 계산되는데
 * `TITLE` 은 전 문서에 있고 `ANCHOR` 는 12~37% 에만 있다. 그래서 제목 사본 앵커는
 * 중복이 아니라 **"이 문서는 실제로 링크된다" 는 증폭기**로 작동한다 — 빼면 ONAP
 * 정답 다섯 중 넷이 앵커를 통째로 잃는다. 상세는
 * `docs/experiment-2026-08-26-title-dup-anchor.md`.
 *
 * **BM25F 라면 둘 다 살릴 수 있을지 모른다** — tf 를 포화 전에 합치므로 증폭기를
 * 유지하면서 중복만 줄인다. 안 재봤다.
 *
 * 측정된 것은 **효과**뿐이다(D28, 2026-08-26 · 코웨이 30질의):
 * 앵커를 끄면 상위10 진입이 17 → 13 으로 준다. 질의별로는 도움 16 · 해침 4 이고,
 * **결과 밖으로 밀어낸 사례는 0건**이라 낮출 근거가 없다. 다른 배수(1·2·3)는
 * 안 재봤다.
 *
 * **그 효과가 코퍼스에 달려 있다.** 같은 대조를 공개 코퍼스(ONAP 15질의)에서
 * 하면 8 → 7 로 거의 안 바뀐다 — 질의와 문서의 어휘가 안 어긋나면 앵커가 메울
 * 격차가 없기 때문이다. **위 숫자로 이 값을 정당화하지 말 것**: 한 코퍼스에서
 * 도움이 컸다는 뜻이지 어디서나 그렇다는 뜻이 아니다.
 */
object FieldBoost {
    const val ANCHOR = 4.0f
    const val TITLE = 3.0f
    const val BODY = 1.0f
}
