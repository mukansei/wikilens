"""
`stats` 의 어휘 격차 측정에 쓰는 토크나이저. 표준 라이브러리만 쓴다.

**검색 경로에 안 쓰인다.** 예전에는 클라이언트와 서버가 각자 토큰화하던 설계라
"양쪽이 반드시 같은 규칙을 써야 한다"가 이 파일의 존재 이유였는데, 그 설계는
폐기됐다 — 지금은 서버가 Nori 로 토큰화하고 클라이언트는 원문만 보낸다
(토크나이저 정본이 하나여야 조용히 0건이 되는 일이 없다). 로컬판은 아예
토큰화하지 않고 ripgrep 으로 찾는다.

그래서 남은 소비자는 `wikilens stats` 하나다. 하는 일은 **"이 앵커와 제목이
검색 엔진 눈에 같은 말인가"의 근사**다:

    제목 `OAuth 2.0 인가 코드 흐름` · 앵커 `로그인 붙이는 법`  → 겹침 없음 = 어휘 격차
    제목 `배포 파이프라인`          · 앵커 `배포 파이프라인을`   → 겹침 있음 = 격차 아님

두 판 중 **어느 쪽의 실제 검색 토크나이저도 아니다.** 대소문자와 조사 정도만
흡수하는 근사이고, 그것으로 충분하다 — 재려는 것이 "이 코퍼스에 어휘 격차가
있는가"라는 도입 판단이지 랭킹 품질이 아니기 때문이다. 그래서 두 판 어느 쪽을
쓰든 같은 수가 나오고, 판을 바꿔도 판단 기준이 흔들리지 않는다.

한국어는 교착어라 조사가 붙는다('로그인을/로그인은'). 형태소 분석기 없이
문자 바이그램을 함께 내면 그 차이가 상당 부분 흡수된다 — `로그인을` 이
`로그인`·`그인을` 을 함께 내므로 `로그인` 과 겹친다.
"""
import re

_WORD = re.compile(r"[A-Za-z0-9_]{2,}|[가-힣]{2,}")
_HANGUL = re.compile(r"^[가-힣]+$")


def tokenize(text: str) -> list[str]:
    out = []
    for m in _WORD.finditer(text.lower()):
        w = m.group(0)
        out.append(w)
        if _HANGUL.match(w) and len(w) > 2:
            out.extend(w[i:i + 2] for i in range(len(w) - 1))
    return out
